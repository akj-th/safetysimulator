/** 원문 대조를 마쳐 인용해도 되는 것만 */
export function verifiedBasis() {
  return LEGAL_BASIS.filter((b) => b.verified);
}

/**
 * 지시문에 넣을 근거 목록 — 대조를 마친 것만, 유형별로 묶어서 넣습니다.
 *
 * 법령·정책은 **인용 문구(`cite`)만** 넣습니다. 요지(`gist`)를 넣으면
 * AI 가 그것을 조문 본문처럼 옮겨 적습니다. 협의 문서만 요지를 넣습니다.
 */
export function legalBlock() {
  const ok = verifiedBasis();
  if (!ok.length) {
    return '(인용할 수 있는 근거 없음 — 법령·정책·협의를 언급하지 말고 basis 에 kind:"확인필요" 로 적으십시오)';
  }

  return ['law', 'policy', 'consult'].map(function (kind) {
    const rows = ok.filter((b) => b.kind === kind);
    if (!rows.length) return '';
    const k = BASIS_KINDS[kind];
    const lines = rows.map(function (b) {
      const head = `- [${b.id}] 이 문구 그대로 인용: "${b.cite}"`;
      const use = `  쓸 수 있는 곳: ${b.useFor.join(', ')}`;
      /* 협의 문서만 요지를 함께 넘깁니다 (원문이 우리 손에 있어 책임질 수 있음) */
      return kind === 'consult' ? `${head}\n  요지: ${b.gist}\n${use}` : `${head}\n${use}`;
    });
    return `[${k.label}] ${k.rule}\n${lines.join('\n')}`;
  }).filter(Boolean).join('\n\n');
}

/**
 * 아직 대조하지 않아 **쓰지 않은** 근거.
 * AI 지시문에는 들어가지 않고, 화면에만 "이런 것이 빠져 있다"고 알립니다.
 */
export const PENDING = LEGAL_BASIS.filter((b) => !b.verified).map((b) => ({
  id: b.id,
  kind: b.kind,
  kindLabel: (BASIS_KINDS[b.kind] || {}).label || b.kind,
  where: b.article === '—' ? b.law : `${b.law} ${b.article}`,
  title: b.title,
}));
