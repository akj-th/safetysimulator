/** 지시문에 넣을 근거 목록 (AI 가 이 밖의 것을 인용하지 못하게 합니다) */
export function legalBlock() {
  return LEGAL_BASIS.map((b) => {
    const where = b.article === '—' ? b.law : `${b.law} ${b.article}`;
    return `- [${b.id}] ${where} (${b.title})\n  요지: ${b.gist}\n  쓸 수 있는 곳: ${b.useFor.join(', ')}`;
  }).join('\n');
}

