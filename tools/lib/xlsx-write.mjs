/* ════════════════════════════════════════════════════════════════════
   아주 작은 엑셀(xlsx) 쓰기 — 라이브러리 없이 (2026-10-27)

   AURI 에 보내는 양식(연계표 등)을 엑셀·한셀에서 바로 열리게 만들 때 씁니다.
   CSV 는 한셀에서 한글이 깨지거나 칸 너비가 없어 읽기 어렵습니다.
     writeXlsx(file, [{ name: '시트이름', rows: [[...], ...], widths: [12, 30, ...] }])
   첫 줄은 머리글(굵게·회색 바탕), 모든 칸은 줄바꿈·위쪽 맞춤. 글자는 inlineStr 로 넣습니다.
   zip 은 tools/lib/hwpx.mjs 의 writeZip 을 그대로 씁니다.
   ════════════════════════════════════════════════════════════════════ */
import fs from 'node:fs';
import { writeZip } from './hwpx.mjs';

const esc = (s) => String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
  .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '');
const colName = (i) => { let s = ''; i++; while (i > 0) { const m = (i - 1) % 26; s = String.fromCharCode(65 + m) + s; i = Math.floor((i - 1) / 26); } return s; };

function sheetXml(sheet) {
  const cols = (sheet.widths || []).map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('');
  const rows = sheet.rows.map((r, ri) => `<row r="${ri + 1}">${r.map((v, ci) => {
    const ref = colName(ci) + (ri + 1);
    const style = ri === 0 ? 1 : 2;
    if (typeof v === 'number' && Number.isFinite(v)) return `<c r="${ref}" s="${style}"><v>${v}</v></c>`;
    return `<c r="${ref}" s="${style}" t="inlineStr"><is><t xml:space="preserve">${esc(v)}</t></is></c>`;
  }).join('')}</row>`).join('');
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>${cols ? `<cols>${cols}</cols>` : ''}<sheetData>${rows}</sheetData></worksheet>`;
}

